// Command htmlentity writes std/src/template/html_entity.c from the
// table of HTML entities of Go's html package (BSD-3-Clause, see
// LICENSE-Go), so that html/template decodes attribute values exactly as
// Go's html.UnescapeString does.
//
//	go run ./std/gen/htmlentity
package main

import (
	"bytes"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"runtime"
	"sort"
	"strconv"
)

func main() {
	src, err := os.ReadFile(filepath.Join(runtime.GOROOT(), "src", "html", "entity.go"))
	if err != nil {
		log.Fatal(err)
	}
	one := regexp.MustCompile(`(?m)^\s*"([A-Za-z0-9;]+)":\s*'(\\[uU][0-9A-Fa-f]+)',`)
	two := regexp.MustCompile(`(?m)^\s*"([A-Za-z0-9;]+)":\s*\{'(\\[uU][0-9A-Fa-f]+)', '(\\[uU][0-9A-Fa-f]+)'\},`)
	type ent struct {
		name   string
		r1, r2 rune
	}
	var ents []ent
	r := func(s string) rune {
		v, _, _, err := strconv.UnquoteChar(s, '\'')
		if err != nil {
			log.Fatal(err)
		}
		return v
	}
	for _, m := range one.FindAllStringSubmatch(string(src), -1) {
		ents = append(ents, ent{m[1], r(m[2]), 0})
	}
	for _, m := range two.FindAllStringSubmatch(string(src), -1) {
		ents = append(ents, ent{m[1], r(m[2]), r(m[3])})
	}
	if len(ents) < 2000 {
		log.Fatalf("only %d entities found", len(ents))
	}
	sort.Slice(ents, func(i, j int) bool { return ents[i].name < ents[j].name })
	var b bytes.Buffer
	b.WriteString("/* Generated by std/gen/htmlentity from Go's html package (BSD-3-Clause,\n   see LICENSE-Go): the HTML entities, sorted by name. DO NOT EDIT. */\n")
	b.WriteString("#include \"template_internal.h\"\n\n")
	b.WriteString("const thtml_entity thtml_entities[] = {\n")
	for _, e := range ents {
		fmt.Fprintf(&b, "\t{%q, 0x%x, 0x%x},\n", e.name, e.r1, e.r2)
	}
	b.WriteString("};\n\n")
	fmt.Fprintf(&b, "const size_t thtml_nentities = %d;\n", len(ents))
	if err := os.WriteFile("std/src/template/html_entity.c", b.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
}
