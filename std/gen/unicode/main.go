// Command unicode writes std/src/unicode/tables.c from the tables of Go's
// unicode package (BSD-3-Clause, see LICENSE-Go), so that AltC's
// <alt/unicode.h> classifies and maps runes exactly as Go does.
//
//	go run ./std/gen/unicode
package main

import (
	"bytes"
	"fmt"
	"log"
	"os"
	"sort"
	"unicode"
)

var categories = []string{
	"L", "Lu", "Ll", "Lt", "Lm", "Lo",
	"M", "Mn", "Mc", "Me",
	"N", "Nd", "Nl", "No",
	"P", "Pc", "Pd", "Ps", "Pe", "Pi", "Pf", "Po",
	"S", "Sm", "Sc", "Sk", "So",
	"Z", "Zs", "Zl", "Zp",
	"C", "Cc", "Cf", "Co", "Cs",
}

var properties = []string{"White_Space"}

func ranges(t *unicode.RangeTable) [][3]uint32 {
	var out [][3]uint32
	for _, r := range t.R16 {
		out = append(out, [3]uint32{uint32(r.Lo), uint32(r.Hi), uint32(r.Stride)})
	}
	for _, r := range t.R32 {
		out = append(out, [3]uint32{r.Lo, r.Hi, r.Stride})
	}
	return out
}

func table(b *bytes.Buffer, name string, t *unicode.RangeTable) {
	r := ranges(t)
	fmt.Fprintf(b, "static const uint32_t %s_r[][3] = {\n", name)
	for i, x := range r {
		fmt.Fprintf(b, "{0x%x, 0x%x, %d},", x[0], x[1], x[2])
		if i%4 == 3 {
			b.WriteString("\n")
		}
	}
	fmt.Fprintf(b, "};\nconst alt_unicode_table alt_unicode_%s = {%s_r, %d, %d};\n\n", name, name, len(r), t.LatinOffset)
}

func main() {
	var b bytes.Buffer
	fmt.Fprintf(&b, "/* Code generated by std/gen/unicode from Go's unicode tables (Unicode %s); DO NOT EDIT.\n", unicode.Version)
	b.WriteString("   BSD-3-Clause, see LICENSE-Go */\n#include <alt/unicode.h>\n\n")
	for _, c := range categories {
		table(&b, c, unicode.Categories[c])
	}
	for _, p := range properties {
		table(&b, p, unicode.Properties[p])
	}
	// case ranges
	b.WriteString("const alt_unicode_case_range alt__unicode_case_ranges[] = {\n")
	for _, c := range unicode.CaseRanges {
		fmt.Fprintf(&b, "{0x%x, 0x%x, {%d, %d, %d}},\n", c.Lo, c.Hi, c.Delta[0], c.Delta[1], c.Delta[2])
	}
	fmt.Fprintf(&b, "};\nconst int alt__unicode_ncase_ranges = %d;\n\n", len(unicode.CaseRanges))
	// SimpleFold where it is not ToLower-else-ToUpper (Go's caseOrbit)
	var orbit [][2]rune
	for r := rune(0); r <= unicode.MaxRune; r++ {
		f := unicode.SimpleFold(r)
		d := unicode.ToLower(r)
		if d == r {
			d = unicode.ToUpper(r)
		}
		if f != d {
			orbit = append(orbit, [2]rune{r, f})
		}
	}
	sort.Slice(orbit, func(i, j int) bool { return orbit[i][0] < orbit[j][0] })
	b.WriteString("const int32_t alt__unicode_orbit[][2] = {\n")
	for _, o := range orbit {
		fmt.Fprintf(&b, "{0x%x, 0x%x},\n", o[0], o[1])
	}
	fmt.Fprintf(&b, "};\nconst int alt__unicode_norbit = %d;\n", len(orbit))
	if err := os.WriteFile("std/src/unicode/tables.c", b.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
}
